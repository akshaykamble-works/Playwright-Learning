/*

Primitive data type: Number
1. Number: Represents numeric values, including integers and floating-point numbers.
 Example: 42, 3.14

*/
let a= 10; // number
console.log(a);
console.log(typeof a);

let price= 99.99; // number
console.log(price);
console.log(typeof price);

let negativeNumber= -5; // number
console.log(negativeNumber);
console.log(typeof negativeNumber);

let zero= 0; // number
console.log(zero);
console.log(typeof zero);

let age= 25; // number
console.log(age);
console.log(typeof age);

// Real time Example:
 let itemPrice= 49.99; // number
 let quantity= 3; // number
 let discount= 10; // number
 let totalCost= itemPrice * quantity; // multiplication
 console.log("Total Cost: " + totalCost);
 console.log('After discount: ' + (totalCost - discount)); // subtraction
 console.log(typeof (totalCost - discount)); // subtraction