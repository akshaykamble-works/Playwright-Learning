/*
Incremental Operators

*/
let num=10;
console.log("Before increment: "+num); // Output: 10

num++; // Increment by 1
console.log("After increment: "+num); // Output: 11

num--; // Decrement by 1
console.log("After decrement: "+num); // Output: 10

// pre-increment
let preIncrement=5;
console.log("Before pre-increment: "+preIncrement); // Output: 5
++preIncrement; // Increment by 1
console.log("After pre-increment: "+preIncrement); // Output: 6

// pre-decrement
let preDecrement=8;
console.log("Before pre-decrement: "+preDecrement); // Output: 8
--preDecrement; // Decrement by 1
console.log("After pre-decrement: "+preDecrement); // Output: 7