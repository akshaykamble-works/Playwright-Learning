/*
Null primitive data type in JavaScript represents the intentional absence of any object value.
It is one of the primitive data types in JavaScript, along with Number, String, Boolean, Undefined, Symbol, and BigInt.
null is intemtionally assigned to a variable to indicate that it has no value or that it is empty.
Example:
let y = null;

Null vs Undefined:

Feature                  | Null                    | Undefined
Meaning.                 | Intentional empty value | not assigned a value
Assinged By              | Assigned by programmer  | Assigned by JavaScript      
Type                     | Object                  | Undefined
Use.                     | Default state           | No Value explicitly assigned

*/

